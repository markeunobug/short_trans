#!/usr/bin/env python3
"""Regenerate TX sine tables and RX ROM from the TX frequency contract."""
from pathlib import Path
import math
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    header = (ROOT / "code/stm32/tx_stm32/Core/Inc/fsk_tx.h").read_text()
    def value(name):
        return int(re.search(r"#define\s+" + name + r"\s+(\d+)", header)[1])
    rate = value("FSK_TX_SAMPLE_RATE_HZ")
    count = value("FSK_TX_SYMBOL_SAMPLES")
    frequencies = [value("FSK_TX_FREQUENCY_BIT0_HZ"), value("FSK_TX_FREQUENCY_BIT1_HZ")]
    # The RTL phase counter and the symbol DMA table both cover 480 samples.
    assert count == 480 and all(f * count % rate == 0 for f in frequencies)
    def q15(x):
        return int(math.copysign(math.floor(abs(x) * 32767 + 0.5), x))
    rows = []
    for n in range(count):
        rows.append(tuple(q15(fn(2 * math.pi * f * n / rate))
                          for f in frequencies for fn in (math.cos, math.sin)))
    tx = ["/* Generated by tools/gen_fsk_tones.py; do not edit tables by hand. */",
          "#ifndef FSK_TONE_TABLES_H", "#define FSK_TONE_TABLES_H", "",
          "/* One 10 ms symbol: 17 cycles at 1700 Hz or 19 cycles at 1900 Hz. */"]
    for bit in range(2):
        tx += [f"static const int16_t s_sine_bit{bit}[FSK_TX_SYMBOL_SAMPLES] = {{"]
        samples = [row[2 * bit + 1] for row in rows]
        tx += ["    " + ", ".join(f"{v:6d}" for v in samples[i:i+8]) + ","
               for i in range(0, count, 8)]
        tx += ["};", ""]
    tx += ["#endif /* FSK_TONE_TABLES_H */", ""]
    (ROOT / "code/stm32/tx_stm32/Core/Inc/fsk_tone_tables.h").write_text("\n".join(tx))
    rtl = ["`timescale 1ns/1ps", "",
           "// Generated by tools/gen_fsk_tones.py from the TX frequency contract.",
           "// 480 samples at 48 kSPS: f0 = 17 cycles (1.7 kHz), f1 = 19 (1.9 kHz).",
           "// Signed Q1.15 coefficients; phase wraps only after a complete symbol.",
           "module fsk_tone_rom (", "    input wire [8:0] phase_index,",
           "    output reg signed [15:0] cos_f0, sin_f0, cos_f1, sin_f1", ");",
           "    always @* begin", "        case (phase_index)"]
    def literal(x):
        return ("-" if x < 0 else "") + f"16'sd{abs(x)}"
    for n, row in enumerate(rows):
        assignments = " ".join(f"{name} = {literal(v)};" for name, v in
                               zip(("cos_f0", "sin_f0", "cos_f1", "sin_f1"), row))
        rtl.append(f"            9'd{n}: begin {assignments} end")
    rtl += ["            default: begin cos_f0 = 16'sd32767; sin_f0 = 16'sd0; cos_f1 = 16'sd32767; sin_f1 = 16'sd0; end",
            "        endcase", "    end", "endmodule", ""]
    (ROOT / "code/cyclone10/rx_cyclone10/rtl/demod/fsk_tone_rom.v").write_text("\n".join(rtl))
    print(f"Generated TX/RX tones: {frequencies} Hz, {count} samples at {rate} SPS")


if __name__ == "__main__":
    main()
