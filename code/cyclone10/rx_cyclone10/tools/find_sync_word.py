#!/usr/bin/env python3
"""Rank every 16-bit 2FSK sync-word candidate reproducibly.

The receiver accepts a sync word with up to one bit error.  Two radius-one
Hamming balls overlap when their centres are at distance two or less, so the
ranking explicitly counts those collisions against cyclic misalignments and
the two alternating preamble phases.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path


WORD_BITS = 16
WORD_MASK = (1 << WORD_BITS) - 1
PREAMBLE_PHASES = (0xAAAA, 0x5555)


def popcount(value: int) -> int:
    return value.bit_count()


def hamming(left: int, right: int) -> int:
    return popcount(left ^ right)


def rotate_left(word: int, shift: int) -> int:
    return ((word << shift) | (word >> (WORD_BITS - shift))) & WORD_MASK


def aperiodic_peak(word: int) -> int:
    """Return the largest bipolar aperiodic sidelobe for overlap >= 4 bits."""
    chips = [1 if word & (1 << (WORD_BITS - 1 - index)) else -1
             for index in range(WORD_BITS)]
    peaks = []
    for shift in range(1, WORD_BITS - 3):
        correlation = sum(
            chips[index] * chips[index + shift]
            for index in range(WORD_BITS - shift)
        )
        peaks.append(abs(correlation))
    return max(peaks)


@dataclass(frozen=True)
class Metrics:
    word: int
    ones: int
    balance_error: int
    alternating_distance: int
    cyclic_min_distance: int
    cyclic_peak_matches: int
    sliding_near_matches: int
    one_bit_collision_count: int
    aperiodic_peak: int

    @property
    def sliding_false_accept_probability(self) -> float:
        # The 15 windows are the non-aligned windows in word || word.
        return self.sliding_near_matches / (WORD_BITS - 1)

    @property
    def score(self) -> tuple[int, ...]:
        # Numeric word is the final tie-break, making the result deterministic.
        return (
            self.one_bit_collision_count,
            self.balance_error,
            -self.alternating_distance,
            self.sliding_near_matches,
            -self.cyclic_min_distance,
            self.aperiodic_peak,
            self.word,
        )


def measure(word: int) -> Metrics:
    cyclic_distances = [
        hamming(word, rotate_left(word, shift))
        for shift in range(1, WORD_BITS)
    ]
    alternating_distances = [hamming(word, phase) for phase in PREAMBLE_PHASES]
    nuisance_distances = cyclic_distances + alternating_distances
    ones = popcount(word)
    return Metrics(
        word=word,
        ones=ones,
        balance_error=abs(ones - WORD_BITS // 2),
        alternating_distance=min(alternating_distances),
        cyclic_min_distance=min(cyclic_distances),
        cyclic_peak_matches=WORD_BITS - min(cyclic_distances),
        sliding_near_matches=sum(distance <= 1 for distance in cyclic_distances),
        one_bit_collision_count=sum(distance <= 2 for distance in nuisance_distances),
        aperiodic_peak=aperiodic_peak(word),
    )


def rank_candidates() -> list[Metrics]:
    candidates = (measure(word) for word in range(1, WORD_MASK))
    return sorted(candidates, key=lambda item: item.score)


def write_header(path: Path, selected: Metrics) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = f"""`ifndef FSK_SYNC_WORD_VH
`define FSK_SYNC_WORD_VH

// Generated by tools/find_sync_word.py. Do not hand-edit.
// Rank 1 metrics: balance={selected.ones}/{WORD_BITS}, alternating_distance={selected.alternating_distance},
// cyclic_min_distance={selected.cyclic_min_distance}, aperiodic_peak={selected.aperiodic_peak}, collisions={selected.one_bit_collision_count}.
`define FSK_SYNC_WORD 16'h{selected.word:04X}

`endif
"""
    path.write_text(text, encoding="ascii", newline="\n")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--top", type=int, default=20, help="number of ranks to print")
    parser.add_argument(
        "--write-header",
        type=Path,
        help="write the rank-one candidate to this Verilog header",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.top < 1:
        raise SystemExit("--top must be positive")

    ranked = rank_candidates()
    print(
        "rank word ones alt_dist cyclic_min cyclic_peak slide<=1 slide_prob "
        "radius1_collisions aperiodic_peak"
    )
    for rank, item in enumerate(ranked[: args.top], start=1):
        print(
            f"{rank:4d} 0x{item.word:04X} {item.ones:4d} "
            f"{item.alternating_distance:8d} {item.cyclic_min_distance:10d} "
            f"{item.cyclic_peak_matches:11d} {item.sliding_near_matches:8d} "
            f"{item.sliding_false_accept_probability:10.6f} "
            f"{item.one_bit_collision_count:18d} {item.aperiodic_peak:14d}"
        )

    selected = ranked[0]
    print(
        f"\nSelected rank 1: 0x{selected.word:04X}; balanced, "
        f"distance {selected.alternating_distance} from both preamble phases, "
        f"minimum cyclic distance {selected.cyclic_min_distance}, and "
        f"{selected.one_bit_collision_count} radius-one nuisance collisions."
    )
    if args.write_header:
        write_header(args.write_header, selected)
        print(f"Wrote {args.write_header}")


if __name__ == "__main__":
    main()
